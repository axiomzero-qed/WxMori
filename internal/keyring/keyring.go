package keyring

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"os"
	"path/filepath"
	"strings"
	"time"

	"github.com/axiomzero-qed/WxMori/internal/cryptodb"
	"github.com/axiomzero-qed/WxMori/internal/fault"
)

// Material contains only locally decoded secrets. It is never serialized to tools.
type Material struct {
	Master []byte
	BySalt map[[16]byte][32]byte
}

func (m *Material) Clear() {
	clear(m.Master)
	for salt := range m.BySalt {
		delete(m.BySalt, salt)
	}
}
func (m *Material) Resolve(page []byte) ([]byte, error) {
	if len(page) != cryptodb.PageSize {
		return nil, fault.New("INVALID_DATABASE_SIZE", "数据库页大小无效 / Invalid database page size", "Use a complete source database.")
	}
	var salt [16]byte
	copy(salt[:], page[:16])
	var enc []byte
	if key, ok := m.BySalt[salt]; ok {
		enc = append([]byte(nil), key[:]...)
	} else if len(m.Master) == 32 {
		enc = cryptodb.Derive(m.Master, salt[:])
	} else {
		return nil, fault.New("DATABASE_KEY_MISSING", "缺少当前数据库密钥 / A database key is missing", "Start capture_key, log in to the selected account, and wait until every required database is verified.")
	}
	mac := cryptodb.MACKey(enc, salt[:])
	ok := cryptodb.Verify(page, mac, 1)
	clear(mac)
	if !ok {
		clear(enc)
		return nil, fault.New("HMAC_FAILED", "数据库密钥校验失败 / Database key authentication failed", "Capture keys for this account again. A key from another account or salt is never accepted.")
	}
	return enc, nil
}

type File struct {
	Version      int               `json:"version,omitempty"`
	Account      string            `json:"account,omitempty"`
	ObtainedAt   string            `json:"obtained_at,omitempty"`
	MasterKey    string            `json:"master_key,omitempty"`
	DatabaseKeys map[string]string `json:"database_keys,omitempty"`
}
type Envelope struct {
	Format    string `json:"format"`
	Protected string `json:"protected"`
}

func AccountID(dir string) string {
	p, _ := filepath.Abs(dir)
	sum := sha256.Sum256([]byte(strings.ToLower(filepath.Clean(p))))
	return hex.EncodeToString(sum[:])
}

func Decode(data []byte, account string) (*Material, error) {
	var envelope Envelope
	if err := json.Unmarshal(data, &envelope); err != nil {
		return nil, invalid()
	}
	if envelope.Format != "" {
		if envelope.Format != "wxmori.dpapi.v1" {
			return nil, invalid()
		}
		var err error
		data, err = unprotect(envelope.Protected)
		if err != nil {
			return nil, err
		}
		defer clear(data)
	}
	var f File
	if err := json.Unmarshal(data, &f); err != nil {
		return nil, invalid()
	}
	if f.Version > 1 {
		return nil, invalid()
	}
	if f.Account != "" && f.Account != account {
		return nil, fault.New("KEY_ACCOUNT_MISMATCH", "密钥文件属于其他数据目录 / Key file belongs to another data directory", "Choose the matching account configuration or capture this account's keys again.")
	}
	m := &Material{BySalt: map[[16]byte][32]byte{}}
	if f.MasterKey != "" {
		key, err := hex.DecodeString(strings.TrimSpace(f.MasterKey))
		if err != nil || len(key) != 32 {
			return nil, invalid()
		}
		m.Master = key
	}
	for saltText, keyText := range f.DatabaseKeys {
		salt, e := hex.DecodeString(saltText)
		key, e2 := hex.DecodeString(keyText)
		if e != nil || e2 != nil || len(salt) != 16 || len(key) != 32 {
			m.Clear()
			return nil, invalid()
		}
		var s [16]byte
		var k [32]byte
		copy(s[:], salt)
		copy(k[:], key)
		m.BySalt[s] = k
		clear(key)
	}
	if len(m.Master) == 0 && len(m.BySalt) == 0 {
		return nil, invalid()
	}
	return m, nil
}
func invalid() error {
	return fault.New("INVALID_KEY_FILE", "密钥文件格式无效 / Invalid key file", "Use a local 64-hex master_key file or a key file generated by WxMori capture. Never paste a key into chat.")
}

func SaveCaptured(path, account string, keys map[[16]byte][32]byte) error {
	f := File{Version: 1, Account: account, ObtainedAt: time.Now().UTC().Format(time.RFC3339), DatabaseKeys: map[string]string{}}
	for salt, key := range keys {
		f.DatabaseKeys[hex.EncodeToString(salt[:])] = hex.EncodeToString(key[:])
	}
	plain, err := json.Marshal(f)
	if err != nil {
		return err
	}
	defer clear(plain)
	sealed, err := protect(plain)
	if err != nil {
		return err
	}
	data, err := json.MarshalIndent(Envelope{Format: "wxmori.dpapi.v1", Protected: sealed}, "", "  ")
	if err != nil {
		return err
	}
	if err = os.MkdirAll(filepath.Dir(path), 0700); err != nil {
		return err
	}
	// An atomic replacement preserves the preceding verified file on interruption.
	tmp, err := os.CreateTemp(filepath.Dir(path), ".wxmori-key-")
	if err != nil {
		return err
	}
	name := tmp.Name()
	defer os.Remove(name)
	if err = tmp.Chmod(0600); err != nil {
		tmp.Close()
		return err
	}
	if _, err = tmp.Write(append(data, '\n')); err != nil {
		tmp.Close()
		return err
	}
	if err = tmp.Sync(); err != nil {
		tmp.Close()
		return err
	}
	if err = tmp.Close(); err != nil {
		return err
	}
	return os.Rename(name, path)
}
